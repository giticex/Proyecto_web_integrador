-- TECHZONE - ESQUEMA H2
-- Compatible con el modelo actual de Spring Boot / JPA

-- 1. LIMPIEZA DE ESTRUCTURAS ANTERIORES

DROP VIEW IF EXISTS historial_compras;

DROP TABLE IF EXISTS detalle_devolucion CASCADE;
DROP TABLE IF EXISTS devolucion CASCADE;
DROP TABLE IF EXISTS detalle_venta CASCADE;
DROP TABLE IF EXISTS venta CASCADE;
DROP TABLE IF EXISTS caja CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP TABLE IF EXISTS persona CASCADE;
DROP TABLE IF EXISTS cliente CASCADE;
DROP TABLE IF EXISTS producto CASCADE;
DROP TABLE IF EXISTS tipo_documento CASCADE;
DROP TABLE IF EXISTS medio_pago CASCADE;
DROP TABLE IF EXISTS parametro CASCADE;

-- 2. PARAMETROS DEL SISTEMA

CREATE TABLE parametro (
    id_parametro VARCHAR(30) PRIMARY KEY,
    valor VARCHAR(50) NOT NULL,
    descripcion VARCHAR(100) NOT NULL
);

-- 3. CATALOGOS

CREATE TABLE tipo_documento (
    id_documento VARCHAR(25) PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL
);

CREATE TABLE medio_pago (
    id_medio_pago VARCHAR(10) PRIMARY KEY,
    descripcion VARCHAR(100) NOT NULL
);

-- 4. PERSONAS Y USUARIOS

CREATE TABLE persona (
    id_persona VARCHAR(25) PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellido VARCHAR(50) NOT NULL,
    fecha_nacimiento DATE,
    correo VARCHAR(100),
    telefono VARCHAR(9),
    usuario VARCHAR(50)
);

CREATE TABLE usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(50) NOT NULL,
    contrasena VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'CLIENTE',
    id_persona VARCHAR(25) NOT NULL,

    CONSTRAINT fk_usuario_persona
        FOREIGN KEY (id_persona)
        REFERENCES persona(id_persona)
);

-- 5. CLIENTES

CREATE TABLE cliente (
    id_cliente VARCHAR(20) PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellido VARCHAR(50) NOT NULL,
    telefono VARCHAR(15),
    contrasena VARCHAR(255) NOT NULL,
    correo VARCHAR(100) UNIQUE
);

-- 6. PRODUCTOS E INVENTARIO

CREATE TABLE producto (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    stock INTEGER NOT NULL,
    precio NUMERIC(10,2) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

-- 7. CAJAS

CREATE TABLE caja (
    id_caja BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,

    fecha_apertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_cierre TIMESTAMP,

    fondo_inicial NUMERIC(12,2) NOT NULL,

    efectivo_esperado NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    tarjeta_esperada NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    transferencia_esperada NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    otros_esperados NUMERIC(12,2) NOT NULL DEFAULT 0.00,

    efectivo_contado NUMERIC(12,2),
    tarjeta_contada NUMERIC(12,2),
    transferencia_contada NUMERIC(12,2),
    otros_contados NUMERIC(12,2),

    diferencia_efectivo NUMERIC(12,2),
    diferencia_tarjeta NUMERIC(12,2),
    diferencia_transferencia NUMERIC(12,2),
    diferencia_otros NUMERIC(12,2),

    observaciones_apertura VARCHAR(500),
    observaciones_cierre VARCHAR(500),

    estado VARCHAR(15) NOT NULL DEFAULT 'ABIERTA',

    CONSTRAINT fk_caja_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
);

-- 8. VENTAS

CREATE TABLE venta (
    id_venta VARCHAR(36) PRIMARY KEY,

    id_cliente VARCHAR(20) NOT NULL,
    id_persona VARCHAR(25) NOT NULL,
    id_caja BIGINT,

    id_tipo_documento VARCHAR(25) NOT NULL,
    numero_documento VARCHAR(36) NOT NULL,
    numero_documento_cliente VARCHAR(15),

    id_medio_pago VARCHAR(10) NOT NULL,

    fecha_emision TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_venta_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES cliente(id_cliente),

    CONSTRAINT fk_venta_persona
        FOREIGN KEY (id_persona)
        REFERENCES persona(id_persona),

    CONSTRAINT fk_venta_caja
        FOREIGN KEY (id_caja)
        REFERENCES caja(id_caja),

    CONSTRAINT fk_venta_tipo_documento
        FOREIGN KEY (id_tipo_documento)
        REFERENCES tipo_documento(id_documento),

    CONSTRAINT fk_venta_medio_pago
        FOREIGN KEY (id_medio_pago)
        REFERENCES medio_pago(id_medio_pago)
);

-- 9. DETALLES DE VENTA

CREATE TABLE detalle_venta (
    id_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_venta VARCHAR(36) NOT NULL,
    id_producto INTEGER NOT NULL,

    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL,

    CONSTRAINT fk_detalle_venta
        FOREIGN KEY (id_venta)
        REFERENCES venta(id_venta),

    CONSTRAINT fk_detalle_producto
        FOREIGN KEY (id_producto)
        REFERENCES producto(id_producto)
);

-- 10. DEVOLUCIONES Y NOTAS DE CREDITO

CREATE TABLE devolucion (
    id_devolucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_venta VARCHAR(36) NOT NULL,
    id_usuario INTEGER NOT NULL,
    id_caja BIGINT,

    numero_nota_credito VARCHAR(40) NOT NULL UNIQUE,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    motivo VARCHAR(255) NOT NULL,
    monto_reembolsado NUMERIC(12,2) NOT NULL,

    estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADA',
    observaciones VARCHAR(500),

    CONSTRAINT fk_devolucion_venta
        FOREIGN KEY (id_venta)
        REFERENCES venta(id_venta),

    CONSTRAINT fk_devolucion_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario),

    CONSTRAINT fk_devolucion_caja
        FOREIGN KEY (id_caja)
        REFERENCES caja(id_caja),

    CONSTRAINT chk_devolucion_monto
        CHECK (monto_reembolsado >= 0)
);

-- 11. DETALLES DE DEVOLUCION

CREATE TABLE detalle_devolucion (
    id_detalle_devolucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_devolucion BIGINT NOT NULL,
    id_detalle_venta INTEGER NOT NULL,

    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,

    motivo VARCHAR(255),

    CONSTRAINT uk_devolucion_detalle
        UNIQUE (id_devolucion, id_detalle_venta),

    CONSTRAINT fk_detalle_devolucion
        FOREIGN KEY (id_devolucion)
        REFERENCES devolucion(id_devolucion),

    CONSTRAINT fk_detalle_venta_original
        FOREIGN KEY (id_detalle_venta)
        REFERENCES detalle_venta(id_detalle),

    CONSTRAINT chk_devolucion_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT chk_devolucion_subtotal
        CHECK (subtotal >= 0)
);

-- 12. INDICES

CREATE INDEX idx_usuario_persona
    ON usuario(id_persona);

CREATE INDEX idx_caja_usuario
    ON caja(id_usuario);

CREATE INDEX idx_caja_estado
    ON caja(estado);

CREATE INDEX idx_caja_fecha
    ON caja(fecha_apertura);

CREATE INDEX idx_venta_cliente
    ON venta(id_cliente);

CREATE INDEX idx_venta_persona
    ON venta(id_persona);

CREATE INDEX idx_venta_caja
    ON venta(id_caja);

CREATE INDEX idx_venta_fecha
    ON venta(fecha_emision);

CREATE INDEX idx_detalle_venta
    ON detalle_venta(id_venta);

CREATE INDEX idx_detalle_producto
    ON detalle_venta(id_producto);

CREATE INDEX idx_devolucion_venta
    ON devolucion(id_venta);

CREATE INDEX idx_devolucion_usuario
    ON devolucion(id_usuario);

CREATE INDEX idx_devolucion_caja
    ON devolucion(id_caja);

CREATE INDEX idx_detalle_devolucion_venta
    ON detalle_devolucion(id_detalle_venta);

-- 13. VISTA DE HISTORIAL DE COMPRAS

CREATE VIEW historial_compras AS
SELECT
    v.id_venta,
    v.fecha_emision,
    td.nombre AS tipo_documento,
    cl.nombre AS cliente,
    cl.apellido,
    pr.nombre AS producto,
    dv.cantidad,
    dv.precio_unitario,
    dv.subtotal,
    mp.descripcion AS medio_pago,
    pe.nombre AS vendedor

FROM venta v

INNER JOIN cliente cl
    ON v.id_cliente = cl.id_cliente

INNER JOIN persona pe
    ON v.id_persona = pe.id_persona

INNER JOIN tipo_documento td
    ON v.id_tipo_documento = td.id_documento

INNER JOIN medio_pago mp
    ON v.id_medio_pago = mp.id_medio_pago

INNER JOIN detalle_venta dv
    ON v.id_venta = dv.id_venta

INNER JOIN producto pr
    ON dv.id_producto = pr.id_producto;
